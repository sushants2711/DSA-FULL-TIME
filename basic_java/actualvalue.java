package basic_java;

public class actualvalue {
    public static void main(String[] args) {
        int x = 10;
        int y = 4;
        int z = 20;

        System.out.println(x + y + z);
        System.out.println("The value of x+y+z is :" + x + y + z);
        System.out.println("The value of x+y+z is :" + (x + y + z));
        System.out.println(x + y + "" + z);
    }
}
